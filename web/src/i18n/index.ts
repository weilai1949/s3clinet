const LS_LOCALE = 's3c.locale'

function readLocale(): Locale {
  try {
    const v = localStorage.getItem(LS_LOCALE) as Locale
    if (v === 'zh-CN' || v === 'en-US') return v
  } catch {
    /* vitest / SSR */
  }
  return 'zh-CN'
}

